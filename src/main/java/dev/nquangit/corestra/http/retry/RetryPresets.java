package dev.nquangit.corestra.http.retry;

import dev.nquangit.corestra.flow.control.StepConditionOperator;

import java.util.List;
import java.util.function.Supplier;

import static dev.nquangit.corestra.flow.control.StepConditionOperator.CONTAINS;
import static dev.nquangit.corestra.flow.control.StepConditionOperator.EQUALS;
import static dev.nquangit.corestra.flow.control.StepConditionOperator.EXISTS;
import static dev.nquangit.corestra.flow.control.StepConditionOperator.IN;
import static dev.nquangit.corestra.flow.control.StepConditionOperator.MATCHES_REGEX;
import static dev.nquangit.corestra.http.retry.RetryConditionSource.RESPONSE_BODY;
import static dev.nquangit.corestra.http.retry.RetryConditionSource.RESPONSE_HEADER;
import static dev.nquangit.corestra.http.retry.RetryConditionSource.STATUS;

/**
 * Starting-point rules for common rate limits and WAF/CDN block pages. Signatures change over time
 * and between deployments; verify each against real responses in the Test view before relying on it.
 *
 * <p>Retrying only helps for rate-based or transient blocks. Signature (payload) blocks, challenge
 * pages and IP bans return the same result on resend, so those presets STOP and highlight the
 * response instead of wasting the wait budget.
 */
public final class RetryPresets {
    private RetryPresets() { }

    /**
     * A named rule template.
     *
     * @param name        display name
     * @param description why and when to use it
     * @param factory     creates a fresh rule (new id) each time
     */
    public record Preset(String name, String description, Supplier<RetryRule> factory) {
        /** Creates a new rule from the template. */
        public RetryRule create() { return factory.get(); }

        @Override public String toString() { return name; }
    }

    /** Returns every preset, rate-limit retries first, then WAF stops, then catch-alls. */
    public static List<Preset> all() {
        return List.of(
                new Preset("Rate limited (429/503)", "Retry generic rate limiting; honors Retry-After.",
                        () -> RetryRule.of("Rate limited (429/503)", RetryRule.Action.RETRY,
                                List.of(c(STATUS, "", IN, "429, 503")))),
                new Preset("Retry-After header present", "Retry any response that tells the client when to come back.",
                        () -> RetryRule.of("Retry-After present", RetryRule.Action.RETRY,
                                List.of(c(RESPONSE_HEADER, "Retry-After", EXISTS, "")))),
                new Preset("Cloudflare rate limit (1015)",
                        "429 from Cloudflare (often error 1015). Retries with a fixed 10 s wait.",
                        () -> RetryRule.of("Cloudflare rate limit", RetryRule.Action.RETRY, List.of(
                                c(STATUS, "", EQUALS, "429"),
                                c(RESPONSE_HEADER, "Server", CONTAINS, "cloudflare"))).withDelayMillis(10_000L)),
                new Preset("Cloudflare challenge (stop)",
                        "Managed/JS challenge pages need a browser; resending will not pass them.",
                        () -> RetryRule.of("Cloudflare challenge", RetryRule.Action.STOP, List.of(
                                c(RESPONSE_HEADER, "cf-mitigated", EQUALS, "challenge"),
                                c(STATUS, "", IN, "403, 503").inGroup(2),
                                c(RESPONSE_HEADER, "Server", CONTAINS, "cloudflare").inGroup(2),
                                c(RESPONSE_BODY, "", MATCHES_REGEX, "Just a moment|challenge-platform").inGroup(2)))
                                .withHighlight(RetryRule.Highlight.ORANGE)),
                new Preset("Cloudflare WAF block (stop)", "Firewall-rule block page (e.g. error 1020).",
                        () -> RetryRule.of("Cloudflare WAF block", RetryRule.Action.STOP, List.of(
                                c(STATUS, "", EQUALS, "403"),
                                c(RESPONSE_HEADER, "Server", CONTAINS, "cloudflare"),
                                c(RESPONSE_BODY, "", MATCHES_REGEX, "Attention Required|error code:?\\s*10(06|07|08|10|12|20)")))
                                .withHighlight(RetryRule.Highlight.RED)),
                new Preset("AWS WAF / CloudFront block (stop)", "403 'Request blocked' generated by CloudFront.",
                        () -> RetryRule.of("AWS WAF block", RetryRule.Action.STOP, List.of(
                                c(STATUS, "", EQUALS, "403"),
                                c(RESPONSE_BODY, "", CONTAINS, "Request blocked"),
                                c(STATUS, "", EQUALS, "403").inGroup(2),
                                c(RESPONSE_HEADER, "X-Cache", CONTAINS, "Error from cloudfront").inGroup(2)))
                                .withHighlight(RetryRule.Highlight.RED)),
                new Preset("Akamai block (stop)", "'Access Denied' page with an Akamai reference number.",
                        () -> RetryRule.of("Akamai block", RetryRule.Action.STOP, List.of(
                                c(STATUS, "", EQUALS, "403"),
                                c(RESPONSE_BODY, "", CONTAINS, "Access Denied"),
                                c(RESPONSE_BODY, "", MATCHES_REGEX, "Reference\\s*#\\s*[0-9a-f.]+")))
                                .withHighlight(RetryRule.Highlight.RED)),
                new Preset("Imperva / Incapsula block (stop)", "Incapsula incident page or X-Iinfo header on a 403.",
                        () -> RetryRule.of("Imperva block", RetryRule.Action.STOP, List.of(
                                c(RESPONSE_BODY, "", CONTAINS, "Incapsula incident ID"),
                                c(STATUS, "", EQUALS, "403").inGroup(2),
                                c(RESPONSE_HEADER, "X-Iinfo", EXISTS, "").inGroup(2)))
                                .withHighlight(RetryRule.Highlight.RED)),
                new Preset("F5 BIG-IP ASM block (stop)", "'The requested URL was rejected' page with a support ID.",
                        () -> RetryRule.of("F5 ASM block", RetryRule.Action.STOP, List.of(
                                c(RESPONSE_BODY, "", CONTAINS, "The requested URL was rejected")))
                                .withHighlight(RetryRule.Highlight.RED)),
                new Preset("Gateway error (502/504)",
                        "Transient upstream errors. Retrying non-idempotent requests may repeat side effects.",
                        () -> RetryRule.of("Gateway error (502/504)", RetryRule.Action.RETRY,
                                List.of(c(STATUS, "", IN, "502, 504")))),
                new Preset("Application 403 (stop)",
                        "Catch-all placed after WAF rules: any other 403 is a real denial; never retried.",
                        () -> RetryRule.of("Application 403", RetryRule.Action.STOP,
                                List.of(c(STATUS, "", EQUALS, "403")))));
    }

    private static RetryCondition c(RetryConditionSource source, String selector, StepConditionOperator operator,
                                    String value) {
        return RetryCondition.of(source, selector, operator, value);
    }
}
